// --- JSON dialects: Claude Code, Cursor -------------------------------------

type jsonAgent struct{ name, path, dialect string }

func (a jsonAgent) Name() string     { return a.name }
func (a jsonAgent) Location() string { return a.path }
func (a jsonAgent) Detect() bool {
	_, err := os.Stat(a.path)
	return err == nil
}

func (a jsonAgent) Render(ms []manifest.Manifest, opts Options) (map[string][]byte, error) {
	root, err := readJSONObject(a.path)
	if err != nil {
		return nil, err
	}
	servers := map[string]entry{}
	for _, m := range ms {
		servers[m.Name] = toEntry(m, opts, selfExe())
	}
	root[a.dialect] = servers
	out, err := json.MarshalIndent(root, "", "  ")
	if err != nil {
		return nil, err
	}
	return map[string][]byte{"": out}, nil
}

